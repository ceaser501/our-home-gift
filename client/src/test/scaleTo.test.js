import { describe, expect, it } from 'vitest';

// 사진첩 훑기가 사진을 얼마나 키우고 줄이는지.
//
// 이 규칙이 어긋나면 화면에는 아무 일도 안 일어난다. 그냥 그 기프티콘만 목록에서
// 조용히 빠진다. 카톡으로 받은 배스킨라빈스 카드(404x677)가 그랬다 — 훑기로는 안
// 나오는데 같은 사진을 직접 등록으로 올리면 읽혔다.
//
// 두 길의 배율이 달랐다. 직접 등록은 analyzeScale이 Math.min(2, ...)로 묶어둬서 정확히
// 2배, 훑기는 1600에 맞추려고 2.363배. 배율이 정수면 원본 픽셀 하나가 출력 픽셀 넷에
// 그대로 떨어지는데, 비정수면 경계가 픽셀 사이에 걸쳐 검정과 흰색이 섞인다. 바코드는
// 그 경계가 전부라 얇은 막대가 회색에 묻힌다.

const { scaleTo } = await import('../utils/gallery');

describe('훑기의 확대·축소 배율', () => {
  // 배스킨라빈스 카드가 정확히 이 자리다.
  it('키울 때는 정수배로만 키운다', () => {
    expect(scaleTo(404, 677, 1600)).toBe(2);
    expect(scaleTo(404, 677, 3200)).toBe(4);
  });

  it('목표에 조금 못 미쳐도 정수배를 지킨다', () => {
    // 1600 / 900 = 1.78. 목표를 넘기더라도 2배로 키운다 — 캔버스가 조금 커질 뿐이고,
    // 1배로 두면 작은 사진을 키우려던 뜻이 없어진다.
    expect(scaleTo(600, 900, 1600)).toBe(2);
  });

  // 줄이는 쪽은 그대로다. 여기서 정수로 묶으면 큰 사진이 통째로 안 줄어든다.
  it('줄일 때는 목표에 맞춘다', () => {
    expect(scaleTo(3000, 4000, 1600)).toBeCloseTo(0.4, 5);
  });

  it('이미 목표 크기면 손대지 않는다', () => {
    expect(scaleTo(1200, 1600, 1600)).toBe(1);
  });
});
