// 앱이 새 판으로 올라오면 폰에 남은 '계산해둔 값'을 버린다.
//
// ── 왜 ──────────────────────────────────────────────────────────────────────
//
// "업데이트해서 들어가면 이상한데 지우고 새로 까니까 된다"가 있었다. 앱을 껐다 켜도
// 그대로였다. 지우고 깔면 낫는다는 것은 곧 폰에 남은 값 때문이라는 뜻이다 — 지우는
// 순간 없어지는 것이 그것뿐이라서다.
//
// 어느 값이었는지는 끝내 못 짚었다. 그래서 하나를 고치는 대신, 이런 일이 다시 나지
// 않게 만든다: 판이 바뀌면 계산해둔 값은 버리고 처음부터 다시 구한다.
//
// ── 무엇을 버리고 무엇을 남기나 ─────────────────────────────────────────────
//
// 버리는 것은 '다시 구할 수 있는 값'뿐이다. 위치, 주변 매장을 찾아둔 결과, 화면 크기.
// 없으면 앱이 다시 구하면 그만이고, 그 사이 잠깐 느릴 뿐이다.
//
// 남기는 것은 '사람이 정한 값'이다. 어두운 모드, 알림을 켰는지, 자동 찾기를 켰는지,
// 마지막으로 본 가족, 첫 설정 화면을 봤는지, 아니라고 해둔 사진들. 이건 다시 구할 수
// 있는 것이 아니라 사람이 손으로 정한 것이라, 업데이트했다고 없어지면 안 된다.
//
// 그 경계가 이 파일의 전부다. 새 값을 만들 때는 어느 쪽인지부터 정하고, 계산해둔
// 값이면 아래 목록에 넣는다.

const VERSION_KEY = 'moacon:app-version';

// 판이 바뀌면 버릴 것들. 전부 다시 구할 수 있는 값이다.
const CACHES = [
  // 주변 매장을 찾아둔 결과. 다음에 앱을 열 때 다시 찾는다.
  'nearby-banner:result',
  // 마지막으로 잡아둔 좌표. 다음에 앱을 열 때 다시 잡는다.
  //
  // 이게 제일 의심스러운 자리였다. 위치를 새로 못 잡으면 이 값으로 물러서는데,
  // 그때 그 값이 다른 동네 것이면 거기서 매장을 찾는다 — 코앞에 매장이 있어도
  // '없어요'가 뜨고, 앱을 껐다 켜도 그대로다(30분이 지나야 버려진다).
  'moacon:position',
  // 화면 크기. 폰 설정을 보고 다시 정한다.
  'moacon:ui-scale',
];

/**
 * 판이 바뀌었으면 계산해둔 값을 버린다. 처음 깐 폰에서는 버릴 것이 없다.
 *
 * 화면이 그려지기 전에 부른다. 그려진 뒤에 버리면 이미 그 값으로 한 번 그린 뒤다.
 */
export function dropStaleCaches(version) {
  try {
    const seen = window.localStorage.getItem(VERSION_KEY);
    if (seen === version) return false;

    // 처음 깐 폰(seen이 없음)에서도 적어두기만 하고 넘어간다. 버릴 것이 없다.
    if (seen) {
      for (const key of CACHES) window.localStorage.removeItem(key);
    }
    window.localStorage.setItem(VERSION_KEY, version);
    return Boolean(seen);
  } catch {
    // 사생활 보호 모드 등. 못 버려도 앱은 그대로 돈다.
    return false;
  }
}
