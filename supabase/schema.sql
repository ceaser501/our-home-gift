-- 어느 공지를 읽었는지. 기기가 아니라 계정에 적는다.
--
-- 종 배지가 안 읽은 활동과 안 읽은 공지를 함께 세기 때문이다. 활동 읽음은 서버에
-- 있는데(activity_reads) 공지 읽음만 기기에 있으면, 한 폰에서 읽고 다른 폰에서 보면
