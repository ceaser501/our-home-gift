-- 기프티콘을 어느 가족 소유로 볼지 표시하는 컬럼
alter table public.gifticons add column if not exists family_id uuid references public.families(id);

-- 카드에 붙는 이름표 색(0부터 시작하는 팔레트 번호). 예전에는 화면에서 "가족 목록의 몇 번째
-- 사람인가"로 색을 정했는데, 누가 빠지면 남은 사람들 색이 통째로 밀리는 문제가 있었다.
-- 그래서 가족에 들어오는 시점에 번호를 받아 두고, 그 뒤로는 바뀌지 않게 한다.
alter table public.family_members add column if not exists tag_color smallint;

-- 이미 있는 멤버는 지금까지 화면에 보이던 색(가입 순서)을 그대로 굳혀서 채운다.
with numbered as (
  select id, (row_number() over (partition by family_id order by created_at) - 1) as idx
  from public.family_members
  where tag_color is null
)
update public.family_members fm
set tag_color = numbered.idx
from numbered
where fm.id = numbered.id;

-- 그 가족에서 아직 안 쓴 가장 작은 색 번호. 여섯 색을 다 쓰면 처음(0)부터 다시 돌려쓴다.
-- 색 개수는 화면 쪽 팔레트(client/src/components/GifticonCard.jsx)와 맞춰야 한다.
create or replace function public.next_tag_color(fid uuid)
returns smallint
language sql
security definer
set search_path = public
stable
as $$
  select coalesce(min(candidate), 0)::smallint
  from generate_series(0, 5) as candidate
  where candidate not in (
    select coalesce(tag_color, -1) from public.family_members where family_id = fid
  );
$$;

-- 내가 이 family에 속해 있는지 확인하는 헬퍼 함수.
-- security definer라서 family_members 자체에 RLS가 걸려 있어도(재귀 없이) 안전하게 조회한다.
create or replace function public.is_family_member(fid uuid)
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.family_members fm
    where fm.family_id = fid and fm.user_id = auth.uid()
  );
$$;

-- 가족 생성: families row + 만든 사람을 첫 멤버로 등록. 초대 코드는 6자리로 자동 생성.
create or replace function public.create_family(family_name text, member_name text)
returns public.families
language plpgsql
security definer
set search_path = public
as $$
declare
  new_family public.families;
  code text;
  attempt int := 0;
begin
  if auth.uid() is null then
    raise exception '로그인이 필요해요.';
  end if;

  loop
    code := upper(substr(md5(random()::text || clock_timestamp()::text), 1, 6));
    begin
      insert into public.families (name, invite_code, created_by)
      values (family_name, code, auth.uid())
      returning * into new_family;
      exit;
    exception when unique_violation then
      attempt := attempt + 1;
      if attempt > 5 then
        raise exception '초대 코드 생성에 실패했어요. 다시 시도해주세요.';
      end if;
    end;
  end loop;

  -- 가족을 만든 사람이 첫 멤버라 이름표 색은 항상 0번.
  insert into public.family_members (family_id, user_id, display_name, tag_color)
  values (new_family.id, auth.uid(), member_name, 0);

  return new_family;
end;
$$;

-- 초대 코드로 가족에 들어오는 일은 request_join_family()(승인 필요)로만 한다.
--
-- 예전의 join_family()는 코드만 맞으면 승인 없이 바로 넣어줬다. 화면에서 부르지 않게 고쳐도
-- 함수가 데이터베이스에 남아 있으면 소용이 없다. 로그인만 했으면 누구나 REST로 직접
-- (POST /rest/v1/rpc/join_family) 부를 수 있어서, 코드를 아는 사람은 승인 절차를 통째로
-- 건너뛸 수 있다. 그래서 함수 자체를 지운다. 인자 조합이 다른 옛 버전이 남아 있을 수도 있어
-- 이름이 같은 것을 모두 지운다.
--
-- 파일 앞쪽에서 지우는 이유: 뒤에서 오류가 나 스크립트가 중간에 멈추더라도, 우회로만은
-- 확실히 막혀 있어야 하기 때문이다.
do $$
declare
  victim record;
begin
  for victim in
    select p.oid::regprocedure as sig
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.proname = 'join_family'
  loop
    execute format('drop function if exists %s', victim.sig);
  end loop;
end $$;

-- 가족에서 나가기. 내가 등록했거나 내 앞으로 되어 있는 기프티콘은 남은 가족에게 안 보이도록
-- 감춘 뒤(지우지는 않는다) 구성원 목록에서 빠진다. 다시 초대 코드로 들어올 수는 있지만,
-- 감춘 기프티콘이 저절로 되살아나지는 않는다.
--
-- 마지막 한 사람이 나가면 그 가족은 통째로 지운다. 빈 가족을 남겨두면 아무도 볼 수 없는
-- 기프티콘만 쌓이고, 초대 코드는 그대로 살아 있는데 승인해줄 사람이 없어서 그 코드를 아는
-- 사람은 누구나 승인 없이 들어와진다(request_join_family의 "구성원 0명" 예외).
--
-- 지워진 기프티콘의 사진 파일 경로를 돌려준다. 스토리지 파일은 SQL에서 지울 수 없어서
-- 부른 쪽이 이어서 지운다.
-- 예전에는 아무것도 돌려주지 않던 함수라, 돌려주는 값이 생긴 지금은 지웠다 다시 만들어야 한다
-- (create or replace로는 반환 타입을 바꿀 수 없다).
drop function if exists public.leave_family(uuid);
create or replace function public.leave_family(fid uuid)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  my_name text;
  orphan_paths text[] := '{}';
  family_deleted boolean := false;
begin
  select display_name into my_name
  from public.family_members
  where family_id = fid and user_id = auth.uid();

  if my_name is null then
    raise exception '이 가족의 구성원이 아니에요.';
  end if;

  delete from public.family_members where family_id = fid and user_id = auth.uid();

  if exists (select 1 from public.family_members where family_id = fid) then
    update public.gifticons
    set hidden_at = now()
    where family_id = fid
      and hidden_at is null
      and (created_by = auth.uid() or owner = my_name);

    -- 내가 찜해둔 것은 풀어준다. 나간 사람이 쓰러 갈 리 없는데 표시만 남아 있으면
    -- 남은 가족이 "저건 누가 쓰기로 했나 보다" 하고 계속 비켜 간다.
    update public.gifticons
    set claimed_by = null, claimed_by_name = null, claimed_at = null
    where family_id = fid and claimed_by = auth.uid();
  else
    select coalesce(array_agg(p), '{}') into orphan_paths
    from (
      select unnest(image_paths) as p from public.gifticons where family_id = fid
      union all
      select barcode_image_path from public.gifticons where family_id = fid and barcode_image_path is not null
    ) t;

    delete from public.gifticons where family_id = fid;
    -- family_members / family_join_requests / push_subscriptions는 따라서 지워진다.
    delete from public.families where id = fid;
    family_deleted := true;
  end if;

  return json_build_object('family_deleted', family_deleted, 'image_paths', orphan_paths);
end;
$$;

-- 내 이름 바꾸기. 기프티콘의 "받은 사람"과 사용 내역에는 이름이 글자 그대로 적혀 있어서,
-- 구성원 이름만 바꾸면 예전 기록이 남남처럼 떨어져 나간다(카드의 이름표 색도 안 맞게 된다).
-- 그래서 이 가족 안에 남아 있는 내 이름들을 같이 옮겨준다.
create or replace function public.rename_member(fid uuid, new_name text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  clean_name text := btrim(new_name);
  old_name text;
begin
  if auth.uid() is null then
    raise exception '로그인이 필요해요.';
  end if;
  if clean_name = '' then
    raise exception '이름을 입력해주세요.';
  end if;
  if char_length(clean_name) > 20 then
    raise exception '이름은 20자까지 쓸 수 있어요.';
  end if;

  select display_name into old_name
  from public.family_members
  where family_id = fid and user_id = auth.uid();

  if old_name is null then
    raise exception '이 가족의 구성원이 아니에요.';
  end if;
  if old_name = clean_name then
    return;
  end if;

  -- 같은 이름이 둘이면 "받은 사람"이 누구인지 구분할 수 없다.
  if exists (
    select 1 from public.family_members
    where family_id = fid and user_id <> auth.uid() and display_name = clean_name
  ) then
    raise exception '가족 중에 같은 이름을 쓰는 사람이 있어요.';
  end if;

  update public.family_members
  set display_name = clean_name
  where family_id = fid and user_id = auth.uid();

  update public.gifticons
  set owner = clean_name
  where family_id = fid and owner = old_name;

  update public.gifticons
  set used_by_name = clean_name
  where family_id = fid and used_by = auth.uid();
end;
$$;

-- 가족 이름 바꾸기. 가족 안에서는 서로 같은 권한이라 구성원이면 누구나 바꿀 수 있다.
create or replace function public.rename_family(fid uuid, new_name text)
returns public.families
language plpgsql
security definer
set search_path = public
as $$
declare
  clean_name text := btrim(new_name);
  updated public.families;
begin
  if not public.is_family_member(fid) then
    raise exception '이 가족의 구성원이 아니에요.';
  end if;
  if clean_name = '' then
    raise exception '가족 이름을 입력해주세요.';
  end if;
  if char_length(clean_name) > 20 then
    raise exception '가족 이름은 20자까지 쓸 수 있어요.';
  end if;

  update public.families set name = clean_name where id = fid returning * into updated;
  return updated;
end;
$$;

