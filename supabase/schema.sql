  read_at timestamptz not null default now(),
  primary key (user_id, notice_id)
);

alter table public.notice_reads enable row level security;

drop policy if exists "notice_reads own" on public.notice_reads;
create policy "notice_reads own" on public.notice_reads
  for all to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

-- ===================== 앱 안 알림 (가족 활동) =====================

-- 가족이 기프티콘을 쓰거나 올리면 목록이 조용히 바뀔 뿐이라, "이거 누가 썼지?"를 알 방법이
-- 없었다. 그렇다고 폰을 울릴 일은 아니다. 그래서 푸시로는 보내지 않고 앱 안에서만 쌓아둔다.
--
-- 푸시로 나가는 것(유효기한 임박, 가족 참여 신청)과 성격이 다르다. 그 둘은 앱을 안 열고
-- 있어도 지금 알아야 하는 일이고, 이건 다음에 앱을 열었을 때 알면 되는 일이다.
--
-- 찜은 넣지 않는다. 찜/해제를 반복하면 목록이 시끄러워지는데, 누가 찜했는지는 이미
-- 카드 버튼에 "○○ 찜"으로 적혀 있어서 여기서 또 알릴 이유가 없다.
create table if not exists public.activities (
  id bigint generated by default as identity primary key,
  family_id uuid not null references public.families(id) on delete cascade,
  -- 'created'(등록) | 'used'(사용완료) | 'unused'(사용취소)
  kind text not null,
  actor_id uuid references auth.users(id) on delete set null,
  -- 이름을 따로 적어두는 이유는 used_by_name과 같다. 그 사람이 가족에서 나가거나 계정을
  -- 지워도 "누가 했는지"는 기록에 남아 있어야 한다.
  actor_name text,
  gifticon_id bigint references public.gifticons(id) on delete set null,
  -- 기프티콘이 지워져도 "무엇을 썼는지"는 남아야 해서 이름도 함께 적어둔다.
  gifticon_name text not null,
  -- 금액권을 쓴 경우 이번에 쓴 금액. 나머지 활동에서는 비어 있다.
  amount integer,
  created_at timestamptz not null default now()
);

alter table public.activities add column if not exists amount integer;

create index if not exists activities_family_idx on public.activities (family_id, created_at desc);

alter table public.activities enable row level security;

-- 우리 가족 것만 본다. 쓰기 정책은 두지 않는다. 기록은 아래 트리거가 남기므로 브라우저에서
-- 직접 넣을 일이 없고, 넣을 수 있으면 있지도 않은 일을 지어낼 수 있다.
drop policy if exists "activities select family" on public.activities;
create policy "activities select family" on public.activities
  for select to authenticated
  using (public.is_family_member(family_id));

-- 기록은 화면이 아니라 데이터베이스가 남긴다. 화면 코드에서 "사용완료를 눌렀으니 기록도
-- 남기자"로 하면, 나중에 다른 경로가 생겼을 때(관리자 화면, 일괄 처리 등) 빠뜨린다.
create or replace function public.log_gifticon_activity()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  what text;
  who text;
  spent integer := null;
begin
  if TG_OP = 'INSERT' then
    what := 'created';
  elsif new.status is distinct from old.status then
    what := case when new.status = 'used' then 'used' else 'unused' end;
    -- 금액권을 마지막 한 번에 다 써서 사용완료로 넘어간 경우, 그 마지막 금액도 함께 적는다.
    if new.spent_amount > coalesce(old.spent_amount, 0) then
      spent := new.spent_amount - coalesce(old.spent_amount, 0);
    end if;
  elsif new.spent_amount is distinct from coalesce(old.spent_amount, 0) and new.spent_amount > coalesce(old.spent_amount, 0) then
    -- 금액권을 조금 썼다. 아직 잔액이 남아서 상태는 그대로다.
    what := 'spent';
    spent := new.spent_amount - coalesce(old.spent_amount, 0);
  else
    -- 이름이나 금액만 고친 것은 알릴 일이 아니다.
    return new;
  end if;

  -- ⚠️ 테스트 전용. 출시 전에 이 두 줄을 지운다(client/src/sampleData.js와 함께).
  -- 목데이터는 사람이 올린 것이 아니라 앱이 채워 넣은 것이라 알릴 일이 아니다. 그냥 두면
  -- 목데이터를 넣을 때마다 "태수님이 ○○ 올렸어요"가 아홉 줄씩 쌓이고, 목데이터를 지워도
  -- 그 줄은 남는다(알림은 기프티콘이 지워져도 기록으로 남게 만들어져 있다).
  if new.code like '9000111122%' then
    return new;
  end if;

  -- 가족에서 나간 사람의 기프티콘은 목록에 안 보이므로 알릴 것도 없다.
  if new.family_id is null or new.hidden_at is not null then
    return new;
  end if;

  select display_name into who
  from public.family_members
  where family_id = new.family_id and user_id = auth.uid();

  insert into public.activities (family_id, kind, actor_id, actor_name, gifticon_id, gifticon_name, amount)
  values (new.family_id, what, auth.uid(), coalesce(who, new.used_by_name, new.owner), new.id, new.name, spent);

  return new;
end;
$$;

drop trigger if exists gifticons_activity on public.gifticons;
create trigger gifticons_activity
  after insert or update of status, spent_amount on public.gifticons
  for each row execute function public.log_gifticon_activity();

