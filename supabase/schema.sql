-- ===================== 찜하기 =====================

-- "이건 내가 쓸게"를 가족에게 알려두는 표시. 같은 기프티콘을 두 사람이 쓰러 가는 일을
-- 막는 것이 목적이다.
--
-- 잠금이 아니라 표시다. 찜해둬도 다른 사람이 바코드를 열고 쓸 수 있다. 잠그면 찜해둔
-- 사람이 잊었을 때 아무도 못 쓰게 되는데, 그건 막으려던 것보다 나쁘다.
-- 그래서 찜을 푸는 것은 본인만 할 수 있어도 문제가 되지 않는다.
alter table public.gifticons add column if not exists claimed_by uuid references auth.users(id);
alter table public.gifticons add column if not exists claimed_at timestamptz;
-- 이름을 따로 적어두는 이유는 used_by_name과 같다. 그 사람이 가족에서 나가도 카드에
-- "누가 쓰기로 했는지"는 남아 있어야 한다.
alter table public.gifticons add column if not exists claimed_by_name text;

-- 한 사람만 찜할 수 있다. 둘이 찜하면 애초에 막으려던 중복이 그대로 생긴다.
--
-- 확인하고 나서 쓰는 두 단계로 나누면, 두 사람이 동시에 눌렀을 때 둘 다 "비어 있다"를
-- 읽고 지나간다. 조건을 update의 where에 넣어 한 문장으로 처리한다.
create or replace function public.claim_gifticon(gid bigint)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  my_name text;
  fid uuid;
  taken_by text;
  claimed int;
begin
  select family_id into fid from public.gifticons where id = gid;
  if fid is null then
    raise exception '기프티콘을 찾을 수 없어요.';
  end if;

  select display_name into my_name
  from public.family_members where family_id = fid and user_id = uid;
  if my_name is null then
    raise exception '이 가족의 구성원이 아니에요.';
  end if;

  update public.gifticons
  set claimed_by = uid, claimed_by_name = my_name, claimed_at = now()
  where id = gid and (claimed_by is null or claimed_by = uid);
  get diagnostics claimed = row_count;

  if claimed = 0 then
    select claimed_by_name into taken_by from public.gifticons where id = gid;
    return json_build_object('ok', false, 'claimed_by_name', taken_by);
  end if;

  return json_build_object('ok', true, 'claimed_by_name', my_name);
end;
$$;

-- 찜을 푸는 것은 본인만. 찜은 잠금이 아니라서, 남이 못 풀어도 쓰는 데 지장이 없다.
create or replace function public.release_gifticon(gid bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.gifticons
  set claimed_by = null, claimed_by_name = null, claimed_at = null
  where id = gid and claimed_by = auth.uid();
end;
$$;

grant execute on function public.claim_gifticon(bigint) to authenticated;
grant execute on function public.release_gifticon(bigint) to authenticated;

-- 다 쓴 기프티콘에 "내가 쓸게"가 남아 있으면 헷갈린다. 사용 완료로 바뀌면 찜을 지운다.
create or replace function public.clear_claim_when_used()
returns trigger
language plpgsql
as $$
begin
  if new.status = 'used' and old.status is distinct from 'used' then
    new.claimed_by := null;
    new.claimed_by_name := null;
    new.claimed_at := null;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_clear_claim_when_used on public.gifticons;
create trigger trg_clear_claim_when_used
  before update on public.gifticons
  for each row execute function public.clear_claim_when_used();

-- ===================== 약관 동의 =====================

-- 문서를 만들어 두는 것과 이용자가 동의한 것은 다르다. 동의를 받은 기록이 없으면 약관은
-- 효력을 주장하기 어렵고, 스토어 심사에서도 가입 절차에 동의가 있는지를 본다.
--
-- 만 14세 확인을 함께 받는 이유: 개인정보보호법상 만 14세 미만은 법정대리인 동의가 있어야
-- 개인정보를 수집할 수 있다. 이 앱은 그 절차를 감당할 수 없으므로 만 14세 이상만 받는다.
--
-- 버전을 적어두면 약관을 고쳤을 때 누가 어느 판에 동의했는지 알 수 있고, 다시 받아야 할
-- 사람을 가려낼 수 있다.
create table if not exists public.user_consents (
  user_id uuid primary key references auth.users(id) on delete cascade,
  terms_version text not null,
  privacy_version text not null,
  is_over_14 boolean not null,
  agreed_at timestamptz not null default now()
);

alter table public.user_consents enable row level security;

-- 자기 동의 기록만 보고 남길 수 있다. 고치거나 지우는 정책은 두지 않는다.
-- 동의 기록은 "그때 이렇게 동의했다"는 사실이라 나중에 손대면 기록으로서 의미가 없다.
drop policy if exists "user_consents select own" on public.user_consents;
create policy "user_consents select own" on public.user_consents
  for select to authenticated
  using (user_id = auth.uid());

drop policy if exists "user_consents insert own" on public.user_consents;
create policy "user_consents insert own" on public.user_consents
  for insert to authenticated
  with check (user_id = auth.uid() and is_over_14);

-- 약관을 고쳐 다시 동의를 받아야 할 때는 화면 쪽 버전 값을 올린다. 그러면 예전 판에
-- 동의한 사람에게 동의 화면이 다시 나타나므로, 여기서 기록을 지울 필요가 없다.
drop policy if exists "user_consents update own" on public.user_consents;
create policy "user_consents update own" on public.user_consents
  for update to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid() and is_over_14);

-- ===================== 공지 =====================

-- 운영자가 사용자 전체에게 알리는 글. 가족에 속하지 않는 글이라 family_id가 없다.
--
-- 쓰는 정책을 아예 두지 않는다. 브라우저에서는 어떤 계정으로도 공지를 쓸 수 없고,
-- 운영자가 SQL Editor(또는 서비스 롤)로만 넣는다. "관리자만 쓰기" 같은 정책을 두려면
-- 누가 관리자인지 표시하는 칸이 또 필요한데, 공지 몇 줄 넣자고 권한 체계를 만드는 건
-- 이 앱 크기에 맞지 않는다. 정책이 없으면 RLS가 전부 막으므로 그게 가장 단단하다.
create table if not exists public.notices (
  id bigint generated by default as identity primary key,
  title text not null,
  body text,
  -- 미리 써두고 예약할 수 있게 시작 시각을 둔다. 지금 바로 띄우려면 now()를 넣는다.
  starts_at timestamptz not null default now(),
  -- 언제까지 보여줄지. 비워두면 계속 남는다(예: 이용 안내). 연휴 안내처럼 지나면
  -- 의미 없는 글은 끝 시각을 넣어두면 저절로 내려간다.
  ends_at timestamptz,
  created_at timestamptz not null default now()
);

-- 목록 맨 위 띠에 띄울 만큼 급한 공지인지. 앱 위쪽에는 띠를 하나만 두기로 했고(둘이
-- 겹치면 목록이 두 줄만큼 밀린다), 평소 그 자리는 주변 매장 안내가 쓴다. 중요 공지가
-- 게시 중일 때만 그 자리를 가져간다.
--
-- 중요하지 않은 공지도 사라지지 않는다. 띠에 안 뜰 뿐, 종 아이콘 옆 "공지사항"에는
-- 그대로 쌓인다. 그래서 이 값은 "보여줄까 말까"가 아니라 "끼어들까 말까"에 가깝다.
alter table public.notices add column if not exists is_important boolean not null default false;

-- 마지막으로 손댄 시각. 화면에서 "이 공지를 닫았다"를 기억할 때 id가 아니라 id와 이 값을
-- 함께 쓴다.
--
-- 닫기를 id로만 기억하면, 한 번 닫은 공지는 그 기기에서 영영 다시 못 뜬다. 그런데 운영자가
-- 그 글을 고쳐서 다시 올리거나, 안내성이던 것을 중요로 올리는 일이 있다. 그때는 같은 공지라도
-- 다시 보여줘야 한다 — 사용자가 닫은 것은 "그때의 그 내용"이지 이 글의 모든 판이 아니다.
--
-- 반대로 아무도 손대지 않은 공지가 자꾸 되살아나면 닫기 버튼이 거짓말이 된다. 그래서
-- "고쳤을 때만" 되살아나게 이 값을 기준으로 삼는다.
alter table public.notices add column if not exists updated_at timestamptz not null default now();

create or replace function public.touch_notice_updated_at()
returns trigger
