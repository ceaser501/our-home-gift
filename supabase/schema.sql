-- 오래된 기록은 지운다. 두 달 전에 누가 뭘 썼는지는 아무도 다시 보지 않는데, 안 지우면
-- 가족이 오래 쓸수록 목록만 길어진다. 사용 내역(사용 완료된 기프티콘)은 그대로 남으므로
-- "언제 썼나"를 되짚을 길이 사라지는 것도 아니다.
create or replace function public.purge_old_activities()
returns integer
language sql
security definer
set search_path = public
as $$
  with gone as (
    delete from public.activities where created_at < now() - interval '60 days' returning 1
  )
  select count(*)::integer from gone;
$$;

-- ===================== 외부 API 사용량 =====================

-- 돈이 나가는 기능(AI 분석, 가격 검색, 주변 매장)을 한 사람이 하루에 몇 번 썼는지 센다.
-- 로그인 확인만으로는 부족하다. 계정은 얼마든지 새로 만들 수 있어서, 사람 수가 아니라
-- 계정 수만큼 요금이 나갈 수 있기 때문이다. 여기서 사람당 상한을 둔다.
create table if not exists public.api_usage (
  user_id uuid not null references auth.users(id) on delete cascade,
  action text not null,
  day date not null,
  count int not null default 0,
  primary key (user_id, action, day)
);

-- 사용자가 직접 들여다보거나 고칠 일이 없다. 정책을 하나도 만들지 않아서
-- (RLS는 켜져 있고 정책이 없으면 아무것도 통과하지 못한다) 서버만 다룬다.
alter table public.api_usage enable row level security;

-- 사람별 상한만으로는 부족하다. 계정은 이메일만 있으면 새로 만들 수 있어서, 계정을
-- 갈아치우며 부르면 사람별 상한은 매번 0부터 다시 시작한다. 그래서 "오늘 이 기능이
-- 전부 합쳐 몇 번 쓰였나"도 따로 세고, 거기에도 천장을 둔다. 요금이 얼마까지 나갈 수
-- 있는지를 이 숫자가 정한다.
create table if not exists public.api_usage_total (
  action text not null,
  day date not null,
  count int not null default 0,
  primary key (action, day)
);

alter table public.api_usage_total enable row level security;

-- 세는 일과 판단을 한 문장에서 한다. 나눠서 하면 동시에 여러 번 부를 때 둘 다
-- "아직 여유 있음"으로 읽고 지나가버린다.
-- (인자가 늘어서 예전 것을 지우고 다시 만든다)
drop function if exists public.bump_api_usage(uuid, text, int);
create or replace function public.bump_api_usage(uid uuid, act text, max_per_day int, max_total_per_day int default null)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  today date := (now() at time zone 'utc')::date;
  used int;
  total_used int;
begin
  insert into public.api_usage (user_id, action, day, count)
  values (uid, act, today, 1)
  on conflict (user_id, action, day) do update set count = public.api_usage.count + 1
  returning count into used;

  -- 자기 몫을 넘긴 사람은 여기서 끝낸다. 전체 숫자는 올리지 않는다.
  -- 올려버리면, 한 사람이 계속 두드리는 것만으로 그날 전체 몫이 바닥나서 아무도 못 쓰게
  -- 된다. 막으려던 것(요금)을 막다가 다른 것(서비스 정지)을 내주는 셈이다.
  if used > max_per_day then
    return json_build_object('allowed', false, 'reason', 'user', 'used', used, 'limit', max_per_day);
  end if;

  if max_total_per_day is not null then
    insert into public.api_usage_total (action, day, count)
    values (act, today, 1)
    on conflict (action, day) do update set count = public.api_usage_total.count + 1
    returning count into total_used;

    if total_used > max_total_per_day then
      -- 사용자 잘못이 아니다. 화면에도 다르게 말해야 한다.
      return json_build_object('allowed', false, 'reason', 'total', 'used', used, 'limit', max_per_day);
    end if;
  end if;

  return json_build_object('allowed', true, 'reason', null, 'used', used, 'limit', max_per_day);
end;
$$;

-- 이 함수를 사용자가 부를 수 있으면 남의 사용량을 마음대로 올려 못 쓰게 만들 수 있다.
-- 서버(Edge Function)와, 이 안에서 다시 부르는 security definer 함수만 부른다.
revoke all on function public.bump_api_usage(uuid, text, int, int) from public;
revoke all on function public.bump_api_usage(uuid, text, int, int) from anon;
revoke all on function public.bump_api_usage(uuid, text, int, int) from authenticated;
grant execute on function public.bump_api_usage(uuid, text, int, int) to service_role;

-- 오래된 기록은 쌓아둘 이유가 없다. 이 파일을 실행할 때마다 한 달 지난 것을 치운다.
-- 단 api_usage_total은 치우지 않는다. 사람별 기록(api_usage)은 한도 검사용이라 한 달이면
-- 충분하지만, 전체 기록은 관리자 대시보드(supabase/admin-stats.sql)가 일/월/연 호출 추이를
-- 그리는 원본이다. 하루에 기능당 한 줄이라 몇 년을 쌓아도 부담이 없다.
delete from public.api_usage where day < (now() at time zone 'utc')::date - 30;

-- ===================== 계정 탈퇴 =====================

-- '가족 나가기'와 다르다. 가족 나가기는 그 가족에서만 빠지고 계정과 다른 가족은 그대로지만,
-- 탈퇴는 계정 자체를 없앤다. 그래서 감추는 게 아니라 실제로 지운다.
--
-- 여기서는 데이터만 지운다. auth.users 행은 이 함수의 권한으로 지울 수 없어서,
-- supabase/functions/delete-account가 이 함수를 부른 뒤 사진 파일과 계정을 마저 지운다.
--
-- 남는 것: 다른 가족이 올린 기프티콘(그건 그 가족의 것이다)과, 내가 쓴 사용 내역의 줄.
-- 사용 내역은 가족이 "언제 뭘 썼나"를 보는 기록이라 통째로 지우면 가족 쪽 기록이 비는데,
-- 이름은 남기지 않도록 '탈퇴한 구성원'으로 바꾼다.
create or replace function public.purge_my_data()
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  dead_families uuid[] := '{}';
  doomed bigint[] := '{}';
  paths text[] := '{}';
begin
  if uid is null then
    raise exception '로그인이 필요해요.';
  end if;

  -- 나 혼자 남아 있던 가족은 내가 빠지면 아무도 없으니 통째로 없어진다(가족 나가기와 같다).
  select coalesce(array_agg(fm.family_id), '{}') into dead_families
  from public.family_members fm
  where fm.user_id = uid
    and (select count(*) from public.family_members x where x.family_id = fm.family_id) = 1;

  -- 지울 기프티콘: 내가 올렸거나 내 앞으로 된 것, 그리고 없어질 가족에 남아 있는 것 전부.
  select coalesce(array_agg(g.id), '{}') into doomed
  from public.gifticons g
  where g.family_id = any(dead_families)
     or g.created_by = uid
     or exists (
       select 1 from public.family_members fm
       where fm.family_id = g.family_id and fm.user_id = uid and fm.display_name = g.owner
     );

  select coalesce(array_agg(p), '{}') into paths
  from (
    select unnest(image_paths) as p from public.gifticons where id = any(doomed)
    union all
    select barcode_image_path from public.gifticons where id = any(doomed) and barcode_image_path is not null
    union all
    select thumb_image_path from public.gifticons where id = any(doomed) and thumb_image_path is not null
  ) t;

  delete from public.gifticons where id = any(doomed);

  -- 남는 기프티콘에서 나를 가리키는 것들을 끊는다(계정이 지워지면 이 참조 때문에 막힌다).
  update public.gifticons set used_by = null, used_by_name = '탈퇴한 구성원' where used_by = uid;
  update public.gifticons set created_by = null where created_by = uid;
  update public.gifticons
  set claimed_by = null, claimed_by_name = null, claimed_at = null
  where claimed_by = uid;
  -- 메모를 남긴 사람. 이 줄이 없어서 메모를 한 번이라도 쓴 계정은 탈퇴가 막혔다 —
  -- 데이터는 다 지워지고 마지막 auth.users 삭제에서 이 참조 때문에 거절당한다.
  -- memo_by는 나중에 더한 칸인데 여기를 같이 안 고쳤다.
  update public.gifticons
  set memo_by = null, memo_by_name = '탈퇴한 구성원'
  where memo_by = uid;

  -- 스토리지에 남은 파일의 '주인' 표시.
  --
  -- 사진을 올리면 파일마다 올린 사람이 적히고, 그 칸도 auth.users를 가리킨다. 그래서
  -- 기프티콘을 다 지워도 파일이 남아 있으면 계정 삭제가 거기서 막힌다. 남는 파일은
  -- 늘 있다 — 예전에 지운 기프티콘의 잔여물, 올리다 만 사진 같은 것들이다.
  --
  -- 파일 자체는 여기서 지우지 않는다. 내가 올렸지만 남의 기프티콘에 붙어 있는 사진이
  -- 있을 수 있고(등록한 뒤 다른 사람이 사진을 더한 경우), 그걸 지우면 멀쩡한 기프티콘의
  -- 사진이 사라진다. 주인 표시만 끊는다.
  --
  -- 스토리지는 우리 스키마가 아니라 Supabase 것이라 판이 다를 수 있다(칸 이름이 다르거나
  -- 권한이 없을 수 있다). 그때는 그냥 넘어간다 — 여기서 멈추면 탈퇴 전체가 막힌다.
  begin
    execute 'update storage.objects set owner = null where owner = $1' using uid;
  exception when others then null;
  end;

  delete from public.push_subscriptions where user_id = uid;
  delete from public.family_join_requests where user_id = uid;
  update public.family_join_requests set decided_by = null where decided_by = uid;
  delete from public.family_members where user_id = uid;
  delete from public.families where id = any(dead_families);
  update public.families set created_by = null where created_by = uid;

  return json_build_object(
    'image_paths', paths,
    'deleted_gifticons', coalesce(array_length(doomed, 1), 0),
    'deleted_families', coalesce(array_length(dead_families, 1), 0)
  );
end;
$$;

grant execute on function public.purge_my_data() to authenticated;

-- 탈퇴가 막혔을 때, 무엇이 붙들고 있는지 이름으로 알려준다.
--
-- 이 기능은 같은 자리에서 세 번 막혔다. 그때마다 "이 칸이겠지" 하고 짚어 고쳤고, 세 번 다
-- 틀렸거나 절반만 맞았다. 화면에 오는 말이 "계정을 지우지 못했어요"뿐이라 다음에 볼 곳을
-- 고를 근거가 없었기 때문이다. 그래서 짐작하는 대신 데이터베이스에 직접 묻기로 한다.
--
-- 계정을 지우지 못하게 막을 수 있는 것은 auth.users를 가리키면서 '따라 지우기'도 '비우기'도
-- 아닌 참조뿐이다(confdeltype이 a=아무것도 안 함, r=거절). 그런 칸을 전부 찾아 이 계정을
-- 가리키는 줄이 남아 있는지 세어 본다. 우리 스키마만 보지 않는다 — 지금까지 우리를 막은
-- 것들은 대개 storage처럼 우리가 만들지 않은 자리에 있었다.
create or replace function public.user_delete_blockers(target uuid)
returns table (ref text, rows bigint)
language plpgsql
security definer
set search_path = public
as $$
declare
  r record;
  n bigint;
begin
  for r in
    select con.conrelid::regclass::text as tbl, att.attname::text as col
    from pg_constraint con
    join pg_class ref on ref.oid = con.confrelid
    join pg_namespace refns on refns.oid = ref.relnamespace
    join unnest(con.conkey) as k(attnum) on true
    join pg_attribute att on att.attrelid = con.conrelid and att.attnum = k.attnum
    where con.contype = 'f'
      and refns.nspname = 'auth'
      and ref.relname = 'users'
      and con.confdeltype in ('a', 'r')
  loop
    -- 볼 수 없는 표가 섞여 있어도 나머지는 마저 센다.
    begin
      execute format('select count(*) from %s where %I = $1', r.tbl, r.col) into n using target;
    exception when others then
      n := 0;
    end;
    if n > 0 then
      ref := r.tbl || '.' || r.col;
      rows := n;
      return next;
    end if;
  end loop;
end;
$$;

-- 남의 계정을 넣어 캐볼 수 있으므로 로그인한 사람에게는 주지 않는다. 서버(탈퇴 함수)만 쓴다.
revoke all on function public.user_delete_blockers(uuid) from public, anon, authenticated;
grant execute on function public.user_delete_blockers(uuid) to service_role;

-- ===================== 실시간 반영 =====================

-- 가족 중 누가 기프티콘을 올리거나 가족이 새로 들어오면, 다른 사람 화면에도 새로고침 없이
-- 바로 보이게 한다. 이 publication에 테이블을 넣어둬야 Supabase가 변경 사실을 앱으로 알려준다.
-- (누가 무엇을 받아볼지는 위의 RLS 정책이 그대로 판단하므로, 남의 가족 것은 오지 않는다.)
-- 이미 들어 있으면 다시 넣을 때 오류가 나므로 확인하고 넣는다.
do $$
declare
  target text;
begin
  if not exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    return;
  end if;

  foreach target in array array['gifticons', 'family_members', 'families', 'family_join_requests', 'activities'] loop
    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = target
    ) then
      execute format('alter publication supabase_realtime add table public.%I', target);
    end if;
  end loop;
end $$;
